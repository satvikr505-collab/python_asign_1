# Task 2: Variables and Data Types
# Python determines a variable's type from the value assigned to it.

age = 21
percentage = 78.5
student_name = "Satvik Rai"
is_enrolled = True

print("VARIABLES AND THEIR DATA TYPES")
print("-" * 36)
print("age =", age, "| type:", type(age).__name__)
print("percentage =", percentage, "| type:", type(percentage).__name__)
print("student_name =", student_name, "| type:", type(student_name).__name__)
print("is_enrolled =", is_enrolled, "| type:", type(is_enrolled).__name__)
